const fs = require('fs')
const path = require('path')
const walk = d => fs.readdirSync(d, { withFileTypes: true })
  .flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)])
const files = walk('.').map(f => f.replace(/\\/g, '/').replace(/^\.\//, '')).filter(f => f !== 'INDEX.md')
const idx = fs.readFileSync('INDEX.md', 'utf8')
const refs = [...idx.matchAll(/`((?:zcode|dsh)\/[^`]+?)`/g)].map(m => m[1]).filter(r => !r.includes('*'))
const missing = refs.filter(r => !fs.existsSync(r))
const unlisted = files.filter(f => !refs.some(r => f.startsWith(r.replace(/\/$/, ''))))
console.log('files on disk:', files.length)
console.log('path refs:', refs.length, 'missing:', missing.length)
if (missing.length) console.log('MISSING:\n' + missing.join('\n'))
console.log('files not referenced by index:', unlisted.length)
if (unlisted.length) console.log(unlisted.join('\n'))
